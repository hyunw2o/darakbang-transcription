def _normalize_contextual_homophones(text: str) -> str:
    """
    문맥 기반 혼동어 교정:
    - 수련의/수련회
    - 노회/노예
    - 유초등부/유초동부
    - 교역자/교육자
    - 부교역자/부교육자
    - 신방/심방
    - 쉬고와/기도
    - 대위/대희
    - RBS/RVS
    - 디모데/D 모델
    - CDE/CD (Common Data Elements)
    """
    import re

    if not text:
        return text

    corrected = text

    # 고정 오인식: 유초동부 -> 유초등부
    corrected = re.sub(r"유초\s*동부", "유초등부", corrected)

    # RBS/RVS: 드로아교회 유아유치/비전스쿨 맥락에서는 RVS를 우선 복원
    rvs_context = r"(드로아교회|렘넌트|비전\s*스쿨|비전학교|vision\s*school|유아유치|유치부|유초등부|어린이|학교)"
    corrected = re.sub(rf"((?:{rvs_context})\s*)RBS\b", r"\1RVS", corrected, flags=re.IGNORECASE)
    corrected = re.sub(rf"\bRBS(?=\s*(?:{rvs_context}))", "RVS", corrected, flags=re.IGNORECASE)
    corrected = re.sub(rf"((?:{rvs_context})\s*)알\s*비\s*에스", r"\1RVS", corrected)
    corrected = re.sub(rf"알\s*비\s*에스(?=\s*(?:{rvs_context}))", "RVS", corrected)

    # 디모데/D 모델: 성경/교회 인물 맥락에서는 디모데로 복원
    timothy_context = r"(성경|말씀|신약|사도|바울|서신|디모데전서|디모데후서|딤전|딤후|교회|목회|제자|복음|은혜|기도|설교)"
    corrected = re.sub(
        rf"((?:{timothy_context})\s*)(?:D\s*모델|D모델|디\s*모델|디모델)",
        r"\1디모데",
        corrected,
        flags=re.IGNORECASE,
    )
    corrected = re.sub(
        rf"(?:D\s*모델|D모델|디\s*모델|디모델)(?=\s*(?:{timothy_context}))",
        "디모데",
        corrected,
        flags=re.IGNORECASE,
    )

    # 대위/대희: 군/장교 맥락에서는 대위를 우선 복원
    military_context = r"(군|육군|해군|공군|사관|장교|병사|간부|중위|대위|소위|소령|대령|전역|복무|훈련|부대|사단|연대|대대)"
    corrected = re.sub(rf"((?:{military_context})\s*)대희", r"\1대위", corrected)
    corrected = re.sub(rf"대희(?=\s*(?:{military_context}))", "대위", corrected)

    # 노회/노예: 교단 회의 맥락에서는 노회로 복원
    church_context = r"(총회|교단|장로|목사|헌의|임원|회의|회의록|안건|보고|개최|소집|결정|정기|임시)"
    corrected = re.sub(r"(제\s*\d+\s*)노예", r"\1노회", corrected)
    corrected = re.sub(rf"((?:{church_context})\s*)노예", r"\1노회", corrected)
    corrected = re.sub(rf"노예(?=\s*(?:{church_context}))", "노회", corrected)

    # 수련의/수련회: 문맥(의료 vs 교회 집회)으로 구분
    retreat_context = r"(교회|성회|전도대회|집회|청년|학생|중고등부|유초등부|캠프|수양관|은혜|기도|참가|등록|준비|일정|기간|장소|강사)"
    resident_context = r"(병원|의국|전공의|레지던트|인턴|전문의|진료|환자|의사|의료|당직|수술|임상|과정|교수|파견)"
    corrected = re.sub(rf"((?:{retreat_context})\s*)수련의", r"\1수련회", corrected)
    corrected = re.sub(rf"수련의(?=\s*(?:{retreat_context}))", "수련회", corrected)
    corrected = re.sub(rf"((?:{resident_context})\s*)수련회", r"\1수련의", corrected)
    corrected = re.sub(rf"수련회(?=\s*(?:{resident_context}))", "수련의", corrected)

    # CDE/CD: 의료정보 표준 맥락에서는 CD를 CDE(Common Data Elements)로 복원
    medical_info_context = (
        r"(의료정보|의료\s*데이터|임상데이터|임상\s*데이터|임상연구|임상\s*연구|공통\s*데이터\s*요소|"
        r"Common\s*Data\s*Elements|데이터\s*요소|표준\s*데이터|데이터\s*표준|CDISC|CRF|eCRF|코호트|레지스트리)"
    )
    corrected = re.sub(rf"((?:{medical_info_context})\s*)CD\b", r"\1CDE", corrected, flags=re.IGNORECASE)
    corrected = re.sub(rf"\bCD(?=\s*(?:{medical_info_context}))", "CDE", corrected, flags=re.IGNORECASE)

    # 교역자/교육자, 부교역자/부교육자: 교회 사역 맥락 vs 학교/교육 맥락
    ministry_context = (
        r"(교회|목회|설교|예배|사역|전도|선교|강단|담임|목사|부목사|전도사|장로|권사|집사|청빙|안수|교구|심방|성도|새가족|주일학교|청년부|대학부|학생부|부서|블레싱|Blessing)"
    )
    education_context = (
        r"(학교|학원|수업|교육과정|교사|강사|학생|원장|교감|교장|교무|학부모|시험|성적|반편성|교육청|교실|유치원|초등|중등|고등|대학교|연수|교재)"
    )
    corrected = re.sub(rf"((?:{ministry_context})\s*)교육자", r"\1교역자", corrected)
    corrected = re.sub(rf"교육자(?=\s*(?:{ministry_context}))", "교역자", corrected)
    corrected = re.sub(rf"((?:{education_context})\s*)교역자", r"\1교육자", corrected)
    corrected = re.sub(rf"교역자(?=\s*(?:{education_context}))", "교육자", corrected)
    corrected = re.sub(rf"((?:{ministry_context})\s*)부교육자", r"\1부교역자", corrected)
    corrected = re.sub(rf"부교육자(?=\s*(?:{ministry_context}))", "부교역자", corrected)
    corrected = re.sub(rf"((?:{education_context})\s*)부교역자", r"\1부교육자", corrected)
    corrected = re.sub(rf"부교역자(?=\s*(?:{education_context}))", "부교육자", corrected)
    corrected = re.sub(
        r"\b(유초등부|학생부|청년부|대학부)(교역자|부교역자|교육자|부교육자)\b",
        r"\1 \2",
        corrected,
    )

    # 신방/심방: 교회 방문 사역 맥락에서는 심방으로 복원
    visitation_context = (
        r"(교회|목회|사역|담임|목사|부목사|전도사|장로|권사|집사|교구|성도|가정|새가족|등록|예배|기도|위로|환자|심방|성도님)"
    )
    corrected = re.sub(rf"((?:{visitation_context})\s*)신방", r"\1심방", corrected)
    corrected = re.sub(rf"신방(?=\s*(?:{visitation_context}))", "심방", corrected)

    # 쉬고와/기도: 예배/기도 안내 맥락에서는 '쉬고와'를 '기도'로 복원
    prayer_context = r"(대표|합심|통성|마무리|마침|축도|예배|설교|말씀|헌금|찬송|기도수첩|기도제목|중보|기도회|기도)"
    corrected = re.sub(rf"((?:{prayer_context})\s*)쉬고\s*와", r"\1기도", corrected)
    corrected = re.sub(r"쉬고\s*와(?=\s*(?:하겠습니다|드리겠습니다|합니다|합시다|부탁드립니다))", "기도", corrected)

    # 문장 단위 2차 보정: 인접 단어가 아니어도 같은 문장 내 맥락을 반영
    segments = re.split(r"(\n+|(?<=[.?!？！]))", corrected)
    normalized_segments: list[str] = []
    for segment in segments:
        if not segment or re.fullmatch(r"\n+|[.?!？！]", segment):
            normalized_segments.append(segment)
            continue

        has_ministry = re.search(ministry_context, segment) is not None
        has_education = re.search(education_context, segment) is not None
        has_visitation = re.search(visitation_context, segment) is not None
        has_prayer = re.search(prayer_context, segment) is not None
        if has_ministry and not has_education:
            segment = segment.replace("부교육자", "부교역자").replace("교육자", "교역자")
        elif has_education and not has_ministry:
            segment = segment.replace("부교역자", "부교육자").replace("교역자", "교육자")
        if has_visitation:
            segment = re.sub(r"(?<!\w)신방(?!\w)", "심방", segment)
        if has_prayer:
            segment = re.sub(r"쉬고\s*와", "기도", segment)

        normalized_segments.append(segment)

    corrected = "".join(normalized_segments)

    return corrected


def _normalize_english_contextual_terms(text: str) -> str:
    import re

    if not text:
        return text

    corrected = text
    segments = re.split(r"(\n+|(?<=[.!?])\s+)", corrected)
    normalized_segments: list[str] = []

    church_context = (
        r"(church|sermon|scripture|gospel|pastor|prayer|worship|ministry|grace|faith|"
        r"mission|fellowship|congregation|elder|deacon|benediction|remnant|covenant|"
        r"immanuel|troas|harvester|blessing|prayer journal|acts|psalm|romans|john)"
    )
    medical_info_context = (
        r"(medical data|clinical data|clinical research|common data elements|data standard|"
        r"registry|cohort|CRF|eCRF|CDISC|case report form)"
    )

    for segment in segments:
        if not segment or re.fullmatch(r"\n+|\s+", segment):
            normalized_segments.append(segment)
            continue

        has_church_context = re.search(church_context, segment, flags=re.IGNORECASE) is not None
        has_medical_info_context = re.search(medical_info_context, segment, flags=re.IGNORECASE) is not None

        if has_church_context:
            segment = re.sub(r"\bsalmon\b", "sermon", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bplayer journal\b", "Prayer Journal", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bplayer jernal\b", "Prayer Journal", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bplayer jurnal\b", "Prayer Journal", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bplayer meeting\b", "prayer meeting", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bplayer request(s)?\b", r"prayer request\1", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bplayer topic(s)?\b", r"prayer topic\1", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bclosing player\b", "closing prayer", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bopening player\b", "opening prayer", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\b(?:i|im|em)e?manual\b", "Immanuel", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bblessin[g]?\b", "Blessing", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bbless sing\b", "Blessing", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bmission home\b", "Mission Home", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bprenatal mission home\b", "Prenatal Mission Home", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bharvester mission church\b", "Harvester Mission Church", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\btroas church\b", "Troas Church", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\btrose church\b", "Troas Church", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\btrous church\b", "Troas Church", segment, flags=re.IGNORECASE)

        if has_medical_info_context:
            segment = re.sub(r"\bcommon data element(?:s)?\b", "Common Data Elements", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bc d e\b", "CDE", segment, flags=re.IGNORECASE)
            segment = re.sub(r"\bCD\b", "CDE", segment, flags=re.IGNORECASE)

        normalized_segments.append(segment)

    corrected = "".join(normalized_segments)
    corrected = re.sub(r"(?m)^\s*(well|actually|basically|literally|so|like|you know|i mean)\s*[,.\-:;~?!]+\s*", "", corrected, flags=re.IGNORECASE)
    corrected = re.sub(
        r"(?mi)^((?:Speaker|Participant)\s*(?:[A-Z]|\d+)(?:\s*\([^)]*\))?\s*[:：]\s*)(?:well|actually|basically|literally|so|like|you know|i mean)\s*[,.\-:;~?!]+\s*",
        r"\1",
        corrected,
    )
    return corrected


