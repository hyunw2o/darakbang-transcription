def correct_text(
    text: str,
    transcription_type: str = "sermon",
    language: str = "ko",
    correction_mode: str = "normal",
) -> str:
    """
    1차 텍스트 교정 (규칙 기반)
    transcription_type: "sermon" | "phonecall" | "conversation"
    language: "ko" | "en"
    """
    corrected = text
    import re
    normalized_mode = (correction_mode or "normal").strip().lower()
    if normalized_mode not in {"strict", "normal", "raw"}:
        normalized_mode = "normal"
    if normalized_mode == "raw":
        return re.sub(r"\n{3,}", "\n\n", corrected)

    if language == "en":
        # ===== 영어 교정 =====
        # 영어 일반 STT 오류 교정
        for wrong, right in EN_COMMON_CORRECTIONS.items():
            corrected = re.sub(re.escape(wrong), right, corrected, flags=re.IGNORECASE)

        # 영어 사역/교회 고유명사 교정
        for wrong, right in EN_MINISTRY_CORRECTIONS.items():
            corrected = re.sub(re.escape(wrong), right, corrected, flags=re.IGNORECASE)

        # 영어 의료 용어 교정
        for wrong, right in EN_MEDICAL_CORRECTIONS.items():
            corrected = re.sub(re.escape(wrong), right, corrected, flags=re.IGNORECASE)

        # 영어 문맥 기반 고유명사/약어 교정
        corrected = _normalize_english_contextual_terms(corrected)

        # 영어 성경 구절/책명 형식 정규화
        corrected = _normalize_english_bible_references(corrected)

        # 영어 추임새 제거
        corrected = re.sub(
            r'(?m)^(Um|Uh|So|Like|You know|I mean|Well|Actually|Basically|Literally)[,.\s~?!]+',
            '',
            corrected,
            flags=re.IGNORECASE,
        )
        corrected = re.sub(
            r'(?mi)^((?:Speaker|Participant)\s*(?:[A-Z]|\d+)(?:\s*\([^)]*\))?\s*[:：]\s*)(?:um+|uh+|er+|ah+|hmm+|you know|i mean|like|well|actually|basically|literally)[,.\s~?!]+',
            r'\1',
            corrected,
        )
        corrected = re.sub(r'\n{3,}', '\n\n', corrected)

    else:
        # ===== 한국어 교정 =====
        if transcription_type == "sermon":
            # 설교: strict 모드에서만 전체 교정(강한 치환)을 적용
            if normalized_mode == "strict":
                for wrong, right in COMMON_MISTAKES.items():
                    corrected = corrected.replace(wrong, right)
            else:
                # normal 모드: 과교정을 피하기 위해 일반/안전 치환만 적용
                for wrong, right in GENERAL_CORRECTIONS.items():
                    corrected = corrected.replace(wrong, right)

            # 숫자 패턴 교정 (교회 전용)
            corrected = re.sub(r'이\s*삼\s*칠', '237', corrected)
            corrected = re.sub(r'이백\s*삼십\s*칠', '237', corrected)
            corrected = re.sub(r'오\s*천', '5000', corrected)
            corrected = re.sub(r'칠\s*망대', '7망대', corrected)
            corrected = re.sub(r'칠\s*여정', '7여정', corrected)
            corrected = re.sub(r'칠\s*이정표', '7이정표', corrected)
            corrected = re.sub(r'칠\s*칠\s*칠', '777', corrected)
            # 성경 구절 형식 통일 (예: 사도행전 1장 8절 -> 행1:8)
            corrected = _normalize_korean_bible_references(corrected)
        else:
            # 통화/대화: 일반 한국어 교정만
            for wrong, right in GENERAL_CORRECTIONS.items():
                corrected = corrected.replace(wrong, right)

        # 문맥 기반 혼동어 보정
        corrected = _normalize_contextual_homophones(corrected)

        # 교회명 보정은 '교회' 문맥에서만 수행 (예: 드로에게 교회 → 드로아교회)
        corrected = _normalize_droa_church_mentions(corrected)

        # 의료 용어 교정 (한국어 공통)
        for wrong, right in MEDICAL_CORRECTIONS.items():
            corrected = corrected.replace(wrong, right)

        # 추임새 제거 (한국어 공통)
        corrected = re.sub(r'(?m)^(?:예+|아+|자+|어+|음+|응+|네+|에+|그+|요+)[,.\s~?？！]+', '', corrected)
        corrected = re.sub(
            r'(?m)^((?:화자\s*(?:[A-Z]|\d+)(?:\([^)]*\))?|참석자\s*\d+(?:\([^)]*\))?|Speaker\s*(?:[A-Z]|\d+)(?:\s*\([^)]*\))?|Participant\s*\d+(?:\s*\([^)]*\))?)\s*[:：]\s*)(?:예+|아+|자+|어+|음+|응+|네+|에+|그+|요+)[,.\s~?？！]+',
            r'\1',
            corrected,
        )
        corrected = re.sub(r'(?<=[.?!])\s*(?:예|아|자|어|음|응|네|요)[,~]\s*', ' ', corrected)
        corrected = re.sub(r'\n{3,}', '\n\n', corrected)

    return corrected

